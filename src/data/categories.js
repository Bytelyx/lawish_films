// Helper to look up category by id
export const getCategoryById = (id) => {
  return CATEGORIES.find((cat) => cat.id.toLowerCase() === id.toLowerCase()) || null;
};

// Aggregate all photos across categories for the master /gallery page
export const getAllGalleryPhotos = () => {
  const all = [];
  CATEGORIES.forEach((cat) => {
    cat.images.forEach((img) => {
      all.push({
        ...img,
        categoryId: cat.id,
        categoryTitle: cat.title,
        categoryNumber: cat.number
      });
    });
  });
  return all;
};
